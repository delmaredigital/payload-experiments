const collection = { slug: 'pages', label: 'Pages', contentChecks: true }
const row = (id: number, path: string | null = `/page-${id}`, title = `Page ${id}`, published = false) => ({ id, path, pathKey: path?.replace(/\/$/, '') ?? null, title, published })
const response = (docs: ReturnType<typeof row>[], more = false) => new Response(JSON.stringify({ docs, hasNextPage: more }))
const deferred = () => { let resolve!: (value: Response) => void; const promise = new Promise<Response>(done => { resolve = done }); return { promise, resolve } }
function setup(p = props({ kind: 'page' })) {
  const view = render(<PageCombobox collection={collection} test={p.test} armKey="variantA" apiRoute="/data" />)
  const rerender = () => view.rerender(<PageCombobox collection={collection} test={p.test} armKey="variantA" apiRoute="/data" />)
  return { ...view, p, rerender }
}
const input = () => screen.getByRole('combobox') as HTMLInputElement
const open = () => { input().focus(); fireEvent.click(input()) }
const key = (key: string, altKey = false) => fireEvent.keyDown(input(), { key, altKey })
const active = () => document.getElementById(input().getAttribute('aria-activedescendant') ?? '')
async function search(value: string) {
  vi.useFakeTimers()
  fireEvent.change(input(), { target: { value } })
  await act(async () => vi.advanceTimersByTime(250))
  vi.useRealTimers()
}
